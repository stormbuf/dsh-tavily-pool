/**
 * 惰性加载密钥池（`POOL-1`、`POOL-7`）。
 *
 * **搜索、抓取与面板共用这一份。** 面板路径此前从不触发加载，于是进程重启后只要还没搜索过，
 * 面板读到的就是**空的内存池**；更糟的是它**写**的时候用的也是那份空池——一次「添加密钥」
 * 会把磁盘上原有的密钥全部抹掉。2026-09-20 在隔离实例上复现（ticket `21`）：
 *
 * ```
 * 重启后第一次打开面板     → 面板 keys = 0，磁盘 keys = 3
 * 在面板上加一把新密钥     → 面板 keys = 1，磁盘 keys = 1（原有的 3 把被抹掉）
 * ```
 *
 * 所以「先加载再读、先加载再写」不是优化，而是这条路径的正确性前提。用户看到的现象是
 * 「重启 dsh 后密钥不见了」——数据其实还在文件里，是内存池没被读进来。
 *
 * ## 加载记忆化，但对账每次都做（ticket `22` C1）
 *
 * `load()` 只真正跑一次：它是**建立基线**，反复把整份磁盘文档盖到内存上会把本进程刚做出的
 * 运行期状态（统计、余额）抹掉。但「只加载一次」不等于「此后永不再读磁盘」——用户在进程
 * 运行期间手工编辑 `keys.json` 是算数的（真源语义见 `lib/pool.js` 模块头）。于是这里在
 * 加载之后每次都与磁盘**对账**一次：外部新增的记录立刻可见，外部删掉的记录立刻不再被使用，
 * 而本进程的运行期状态不受影响。
 *
 * @module dsh-tavily-pool/dsh/pool-load
 */

/**
 * 确保密钥池已加载，并与磁盘对账一次。
 *
 * 记忆化是必要的（每个请求都读整份文件、再把它盖到内存上毫无意义），但有两种结果**不能**
 * 被记住：
 *
 * 1. **拒绝**（读盘本身失败）：一次临时性的文件系统故障不该让该进程此后每一次搜索都注定失败。
 * 2. **`loadError`**（文件读到了，但内容是坏的）：`load()` 对这种情况**不抛错**——它按
 *    `POOL-7` 以空池继续，把问题挂在 `loadError` 上。于是「成功兑现」这个事实会把记忆化钉死，
 *    用户手工修好 `keys.json` 之后插件仍会一直用那份空池，直到重启。
 *
 * 注意第 2 条与上面那个数据丢失的耦合：**坏文件期间内存池是空的**，此时任何写入都会把坏文件
 * 换成一个只含新密钥的池。这是 `POOL-7` 明确选择的行为（以空池继续、报错给用户），因此这里
 * 只保证「先读再写」，不改变坏文件的处置方式。
 *
 * 对账（{@link PoolStore#refreshFromDisk}）读不出来时什么都不做，因此它不会把上面这两条
 * 语义搅乱：坏文件不会因为一次对账就把内存里的密钥清掉。
 *
 * @param state - 插件运行时状态；`pool` 缺席（初始化失败）时什么都不做，由调用方按能力不可用处理。
 * @returns 加载与对账都完成的 promise。
 */
export async function ensurePoolLoaded(state) {
  if (state?.pool === undefined || state.pool === null) return;

  state.poolLoad ??= state.pool.load().then((pool) => {
    if (pool.loadError !== undefined) state.poolLoad = undefined;
    return pool;
  }, (error) => {
    // 丢掉失败的 promise，让下一次调用重新读取。
    state.poolLoad = undefined;
    throw error;
  });
  await state.poolLoad;
  await state.pool.refreshFromDisk();
}
